create policy "staff delete orders" on public.orders for delete to authenticated using (public.is_staff());
create policy "staff read self"     on public.staff  for select to authenticated using (user_id = auth.uid());

-- ---------- إرسال الطلب: الأسعار تنحسب من قاعدة البيانات (الزبون ما يقدر يغيرها)
create or replace function public.place_order(p_table int, p_items jsonb, p_note text default null)
returns table (id uuid, order_no bigint, total numeric)
language plpgsql security definer set search_path = public as $$
#variable_conflict use_column
declare
  v_lines  jsonb := '[]'::jsonb;
  v_total  numeric := 0;
  v_tables int;
  v_open   boolean;
  r record;
begin
  select s.tables_count, s.is_open into v_tables, v_open from settings s where s.id = 1;
  if not coalesce(v_open, true) then
    raise exception 'المقهى ما يستقبل طلبات الحين';
  end if;
  if p_table is null or p_table < 0 or p_table > coalesce(v_tables, 50) then
    raise exception 'رقم الطاولة غير صحيح';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 40 then
    raise exception 'الطلب فاضي';
  end if;

  for r in
    select i.id as item_id, i.name as item_name, i.price as item_price, x.qty as qty
    from jsonb_to_recordset(p_items) as x(id bigint, qty int)
    join items i on i.id = x.id and i.available
  loop
    if r.qty is null or r.qty < 1 or r.qty > 20 then
      raise exception 'كمية غير صحيحة';
    end if;
    v_lines := v_lines || jsonb_build_object('id', r.item_id, 'name', r.item_name, 'price', r.item_price, 'qty', r.qty);
    v_total := v_total + r.item_price * r.qty;
  end loop;

  if jsonb_array_length(v_lines) = 0 then
    raise exception 'الأصناف اللي اخترتها غير متوفرة';
  end if;

  return query
    insert into orders as o (table_no, items, note, total)
    values (p_table, v_lines, nullif(left(coalesce(p_note, ''), 200), ''), v_total)
    returning o.id, o.order_no, o.total;
end $$;

-- ---------- تتبع الطلب: الزبون يشوف طلبه بس (لازم يعرف رقمه السري)
create or replace function public.order_status(p_id uuid)
returns table (order_no bigint, status text, total numeric, table_no int, items jsonb, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select o.order_no, o.status, o.total, o.table_no, o.items, o.created_at from orders o where o.id = p_id;
$$;

revoke all on function public.place_order(int, jsonb, text) from public;
revoke all on function public.order_status(uuid) from public;
grant execute on function public.place_order(int, jsonb, text) to anon, authenticated;
grant execute on function public.order_status(uuid) to anon, authenticated;

