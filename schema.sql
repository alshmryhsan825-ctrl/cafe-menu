-- ---------- الجداول
create table if not exists public.settings (
  id           int primary key default 1 check (id = 1),
  cafe_name    text    not null default 'كوفي',
  color        text    not null default '#b5652b',
  currency     text    not null default 'ر.س',
  tables_count int     not null default 12 check (tables_count between 1 and 200),
  is_open      boolean not null default true
);

create table if not exists public.categories (
  id   bigint generated by default as identity primary key,
  name text not null,
  sort int  not null default 0
);

create table if not exists public.items (
  id          bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name        text not null,
  description text,
  price       numeric(10,2) not null check (price >= 0),
  calories    int check (calories >= 0),
  image_url   text,
  emoji       text,
  available   boolean not null default true,
  sort        int not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.orders (
  id         uuid primary key default gen_random_uuid(),
  order_no   bigint generated always as identity,
  table_no   int not null,
  items      jsonb not null,
  note       text,
  total      numeric(10,2) not null,
  status     text not null default 'new' check (status in ('new','accepted','ready','done','rejected')),
  created_at timestamptz not null default now()
);
create index if not exists orders_created_at_idx on public.orders (created_at desc);

-- الموظفين المسموح لهم يدخلون الكاشير ولوحة التحكم
create table if not exists public.staff (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid());
$$;

